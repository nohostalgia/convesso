"""Generates paths-v1.json: the vectors of the path messages (PROTOCOL.md §7).

    python crates/convesso-core/vectors/generate_paths.py

The data of inner types 0x03 (candidates), 0x04 (probe) and 0x05 (probe answer),
built here with Python's `struct` and `ipaddress`, independently of the Rust
encoder. The output is deterministic and committed.
"""

import ipaddress
import json
import pathlib
import struct

HERE = pathlib.Path(__file__).parent
OUT = HERE / "paths-v1.json"
KIND = {"local": 0x00, "public": 0x01, "seen": 0x02}


def endpoint(address, port):
    ip = ipaddress.ip_address(address)
    family = 0x04 if ip.version == 4 else 0x06
    return bytes([family]) + ip.packed + struct.pack("<H", port)


def candidates(generation, entries):
    out = struct.pack("<HB", generation, len(entries))
    for kind, address, port in entries:
        out += bytes([KIND[kind]]) + endpoint(address, port)
    return out


def main():
    lists = [
        ("an empty list", 1, []),
        ("one local IPv4", 2, [("local", "192.168.1.20", 7500)]),
        ("dual-stack, local first", 7, [
            ("local", "192.168.1.20", 7500),
            ("local", "2a01:db8::20", 7500),
            ("public", "2a01:db8::20", 7500),
            ("public", "203.0.113.7", 41641),
        ]),
        ("eight, the most", 65535, [("seen", f"198.51.100.{i}", 1000 + i) for i in range(8)]),
    ]
    nonce = bytes(range(1, 9))
    answers = [
        ("seen over IPv4", nonce, "203.0.113.7", 41641),
        ("seen over IPv6", bytes([0xFF] * 8), "2001:db8::1", 1),
    ]
    malformed = [
        ("empty", b"", "length"),
        ("a count of 9", struct.pack("<HB", 1, 9) + b"".join(
            bytes([0x00]) + endpoint("10.0.0.1", 1) for _ in range(9)), "count"),
        ("a count of 1, no entry", struct.pack("<HB", 1, 1), "length"),
        ("family 0x05", struct.pack("<HB", 1, 1) + bytes([0x00, 0x05]) + bytes(6), "family"),
        ("kind 0x03", struct.pack("<HB", 1, 1) + bytes([0x03]) + endpoint("10.0.0.1", 1), "kind"),
        ("a byte too many", candidates(1, [("local", "10.0.0.1", 1)]) + b"\x00", "length"),
    ]
    probes_malformed = [("a 7-byte probe", bytes(7)), ("a 9-byte probe", bytes(9))]
    answers_malformed = [
        ("no address", nonce),
        ("family 0x05", nonce + bytes([0x05]) + bytes(6)),
        ("IPv4 with 16 bytes", nonce + bytes([0x04]) + bytes(18)),
    ]
    document = {
        "description": "Vectors for PROTOCOL.md, section 7: the data of inner types 0x03, "
        "0x04 and 0x05. Generated by generate_paths.py, independent of the Rust encoder; do not edit.",
        "candidates": [
            {"name": name, "generation": generation,
             "entries": [{"kind": k, "address": a, "port": p} for k, a, p in entries],
             "bytes": candidates(generation, entries).hex()}
            for name, generation, entries in lists
        ],
        "probe": {"nonce": nonce.hex(), "bytes": nonce.hex()},
        "answers": [
            {"name": name, "nonce": n.hex(), "address": a, "port": p,
             "bytes": (n + endpoint(a, p)).hex()}
            for name, n, a, p in answers
        ],
        "malformed_candidates": [
            {"name": name, "bytes": data.hex(), "defect": defect} for name, data, defect in malformed
        ],
        "malformed_probes": [{"name": name, "bytes": data.hex()} for name, data in probes_malformed],
        "malformed_answers": [{"name": name, "bytes": data.hex()} for name, data in answers_malformed],
    }
    OUT.write_text(json.dumps(document, indent=2) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
