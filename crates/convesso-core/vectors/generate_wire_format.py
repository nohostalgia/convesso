"""Generates wire-format.json: the vectors of the convesso wire invariants (PROTOCOL.md §1).

    python crates/convesso-core/vectors/generate_wire_format.py

`mac1` is computed with Python's `hashlib.blake2s`, an implementation independent of the `blake2`
crate the core uses. The output is deterministic and committed; run this again only to add
vectors.
"""

import hashlib
import json
import pathlib

OUT = pathlib.Path(__file__).parent / "wire-format.json"
LABEL = b"convesso-mac1"


def mac1_key(address):
    return hashlib.blake2s(LABEL + address).digest()


def mac1(address, prefix):
    return hashlib.blake2s(prefix, key=mac1_key(address), digest_size=16).digest()


def address(i):
    """A deterministic 32-byte address. mac1 only hashes it, so it need not be a curve point."""
    return hashlib.blake2s(b"convesso test address " + bytes([i])).digest()


def prefix(length):
    return bytes(i % 251 for i in range(length))


def vns(versions, echo):
    return bytes([0x00, len(versions)]) + bytes(versions) + echo


def main():
    # The label bytes as the spec states them.
    assert LABEL == bytes.fromhex("63 6f 6e 76 65 73 73 6f 2d 6d 61 63 31")
    mac1_vectors = []
    for i, length in enumerate([0, 1, 64, 65, 1000]):
        a, p = address(i), prefix(length)
        mac1_vectors.append(
            {"address": a.hex(), "key": mac1_key(a).hex(), "prefix": p.hex(), "mac1": mac1(a, p).hex()}
        )

    echo = mac1(address(0), prefix(65))
    valid = [
        {"name": "one version", "versions": [1]},
        {"name": "two versions", "versions": [1, 7]},
        {"name": "fifteen versions", "versions": list(range(1, 16))},
    ]
    for v in valid:
        v["echo"] = echo.hex()
        v["encoding"] = vns(v["versions"], echo).hex()

    invalid = [
        ("not a version-not-supported message", "NotVersionNotSupported", bytes([0x01, 1, 1]) + echo),
        ("empty", "Truncated", b""),
        ("tag only", "Truncated", bytes([0x00])),
        ("no versions", "EmptyVersionList", bytes([0x00, 0]) + echo),
        ("sixteen versions", "TooManyVersions", vns(list(range(1, 17)), echo)),
        ("one byte short", "WrongLength", vns([1, 2], echo)[:-1]),
        ("one byte long", "WrongLength", vns([1, 2], echo) + b"\x00"),
        ("version 0x00", "ReservedVersion", vns([0x00, 1], echo)),
        ("version 0xff", "ReservedVersion", vns([1, 0xFF], echo)),
        ("decreasing", "VersionsNotIncreasing", vns([2, 1], echo)),
        ("repeated", "VersionsNotIncreasing", vns([1, 1], echo)),
    ]

    document = {
        "description": "Vectors for PROTOCOL.md, section 1. Generated by "
        "generate_wire_format.py with Python's hashlib.blake2s; do not edit.",
        "mac1_label": LABEL.hex(),
        "mac1": mac1_vectors,
        "version_not_supported": {
            "valid": valid,
            "invalid": [{"name": n, "defect": d, "encoding": e.hex()} for n, d, e in invalid],
        },
    }
    OUT.write_text(json.dumps(document, indent=2) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
