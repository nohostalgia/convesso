"""Generates transport-v1.json: the vectors of convesso's transport packets (PROTOCOL.md §5).

    python crates/convesso-core/vectors/generate_transport.py

Uses the pure Python ChaCha20-Poly1305 of generate_dos.py, imported rather than copied, so one
implementation independent of the RustCrypto crates backs every vector. Before writing anything,
it checks that implementation against RFC 8439 §2.8.2, read from
crates/convesso-vectors/src/generated.rs, where it was extracted from the RFC's text; if the check
fails, nothing is written. The output is deterministic and committed.
"""

import hashlib
import json
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))

import generate_dos as aead  # noqa: E402  (the shared pure-Python ChaCha20-Poly1305)

OUT = HERE / "transport-v1.json"


def check_against_rfc8439():
    ciphertext, tag = aead.chacha20_poly1305_seal(
        aead.generated_constant("AEAD_ENCRYPT_KEY"),
        aead.generated_constant("AEAD_ENCRYPT_NONCE"),
        aead.generated_constant("AEAD_ENCRYPT_PLAINTEXT"),
        aead.generated_constant("AEAD_ENCRYPT_AAD"),
    )
    if ciphertext != aead.generated_constant("AEAD_ENCRYPT_CIPHERTEXT") or tag != aead.generated_constant(
        "AEAD_ENCRYPT_TAG"
    ):
        raise SystemExit("ChaCha20-Poly1305 does not reproduce RFC 8439 2.8.2; nothing written")


def seal(key, index, counter, inner_type, data):
    header = bytes([0x01, 0x04]) + struct.pack("<I", index) + struct.pack("<Q", counter)
    nonce = b"\x00" * 4 + struct.pack("<Q", counter)
    ciphertext, tag = aead.chacha20_poly1305_seal(key, nonce, bytes([inner_type]) + data, header)
    return header + ciphertext + tag


def main():
    check_against_rfc8439()
    key_a = hashlib.blake2s(b"convesso test transport key a").digest()
    key_b = hashlib.blake2s(b"convesso test transport key b").digest()
    datagram_1280 = bytes(i % 251 for i in range(1280))
    cases = [
        ("keepalive", key_a, 0x01020304, 0, 0x00, b""),
        ("empty datagram", key_a, 0x01020304, 1, 0x01, b""),
        ("1-byte datagram", key_a, 0x01020304, 2, 0x01, b"\x2a"),
        ("20-byte datagram", key_b, 0xFFFFFFFF, 7, 0x01, bytes(range(20))),
        ("1,280-byte datagram", key_b, 7, 1000, 0x01, datagram_1280),
        ("close, library code 0x0001", key_a, 0x01020304, 3, 0x02, struct.pack("<H", 0x0001)),
        ("close, application code 0x0101", key_b, 9, 4, 0x02, struct.pack("<H", 0x0101)),
        ("reserved inner type 0x03", key_a, 0x01020304, 5, 0x03, b"later"),
        ("the last counter, 2^60 - 1", key_a, 0x01020304, 2**60 - 1, 0x01, b"last"),
    ]
    vectors = []
    for name, key, index, counter, inner_type, data in cases:
        packet = seal(key, index, counter, inner_type, data)
        assert len(packet) == 31 + len(data)
        vectors.append({
            "name": name, "key": key.hex(), "index": index, "counter": counter,
            "inner_type": inner_type, "data": data.hex(), "packet": packet.hex(),
        })
    document = {
        "description": "Vectors for PROTOCOL.md, section 5. Generated by "
        "generate_transport.py, independent of the RustCrypto crates; do not edit.",
        "packets": vectors,
    }
    OUT.write_text(json.dumps(document, indent=2) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
